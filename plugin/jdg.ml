(** Implementation of the [Sulfur Judgment] command.

  [Sulfur Judgment R d] expects [R] to be a new identifier and [d : jdg_desc] to
  be a judgment description over a syntax generated by [Sulfur Syntax].
  It declares [R] as an inductive relation whose constructors are the rules of
  [d] (after a variable rule), and proves it sound and complete with respect to
  the judgment signature derived from [d], then stable under substitution.

  Everything is stated and proved in [theories/JdgDesc.v]:
  this file only computes the constructor types by reduction, and instantiates
  the generic lemmas.
*)

open Prelude
module C = Constants

(** A rule: term, name, names of meta-variables, positions of predicate
  premises. *)
type rule = {
  r_term : EConstr.t ;
  r_name : string ;
  r_binders : string list ;
  r_preds : int list
}

(** The names of the [n] meta-variables of a rule, read off the HOAS binders
  [λ x1 ... xn, _] under [happly] in its conclusion;
  or use [x1 ... xn] when they are not available.
*)
let binder_names (n : int) (concl : EConstr.t) : string list m =
  let* env = get_env in
  let* sigma = get_sigma in
  let default = List.init n (fun i -> "x" ^ string_of_int (i + 1)) in
  let is_happly = EConstr.isRefX env sigma (Lazy.force C.Jdg.happly) in
  let _, body = EConstr.decompose_lambda sigma concl in
  (* The first [happly] application found through the subterms *)
  let rec find t =
    match EConstr.decompose_app sigma t with
    | h, args when is_happly h -> Some args
    | _ ->
      EConstr.fold sigma (fun acc t ->
        match acc with Some _ -> acc | None -> find t
      ) None t
  in
  match find body with
  | Some [| _ ; _ ; _ ; _ ; f ; _ |] ->
    let bs = List.rev (fst (EConstr.decompose_lambda sigma f)) in
    if List.length bs <> n then ret default
    else (
      let name (na, _) =
        match na.Context.binder_name with
        | Names.Name id -> Names.Id.to_string id
        | _ -> "x"
      in
      ret (List.map name bs)
    )
  | _ -> ret default

(** The positions of the predicate premises of a rule *)
let pred_positions (prems : EConstr.t) : int list m =
  let* x = fresh_evar None in
  let* l = decode_list (app prems x) in
  let is_pred =
    decode "a premise" [
      C.Jdg.pd_jdg, (fun _ -> ret false) ;
      C.Jdg.pd_pred, (fun _ -> ret true)
    ]
  in
  let* bs = List.monad_map is_pred l in
  ret (List.concat (List.mapi (fun i b -> if b then [ i ] else []) bs))

let decode_rule (t : EConstr.t) : rule m =
  decode "a rule"
    [
      C.Jdg.build_rule_desc, fun a ->
        let* r_name = decode_string a.(3) in
        let* ps = decode_list a.(4) in
        let* r_binders = binder_names (List.length ps) a.(6) in
        let* r_preds = pred_positions a.(5) in
        ret { r_term = t ; r_name ; r_binders ; r_preds }
    ]
    t

(** The signature and term type of a description, from its type
  [jdg_desc sg T sh]. *)
let decode_sig (desc_ty : EConstr.t) : (EConstr.t * EConstr.t * EConstr.t) m =
  let what = "a judgment description" in
  decode what
    [
      C.list, fun a ->
        decode what
          [ C.Jdg.rule_desc, fun a -> ret (a.(0), a.(1), a.(2)) ]
          a.(0)
    ]
    desc_ty

(** The values of the fields of a [ConcreteSyntax] instance, except [cctor]. *)
let decode_cs_ops (cs : EConstr.t) : EConstr.t list m =
  decode "a ConcreteSyntax instance"
    [ C.CS.build, fun a -> ret [ a.(2) ; a.(3) ; a.(4) ; a.(5) ; a.(6) ] ]
    cs

let generate_desc (name : Names.Id.t) (desc : EConstr.t) : unit =
  let sname = Names.Id.to_string name in
  let mk s = Names.Id.of_string_soft (sname ^ s) in
  (* [map] over a variable context, in a predicate, keeps its name *)
  let reduce_only = reduce_only ~refold:[ const_of_ref (Lazy.force C.map) ] in
  (* The signature of the description, the term type, the shapes, the instance
     and its laws, the rules. *)
  let sg, ty, sh, cs, cl, rules =
    monad_run begin
      let* desc_ty = typecheck desc None in
      let* sg, ty, sh = decode_sig desc_ty in
      let* cs = resolve_tc (apps (mkglob' C.CS.typ) [| sg ; ty |]) in
      let* cl = resolve_tc (apps (mkglob' C.CS.laws) [| sg ; ty ; cs |]) in
      let* rules = decode_list desc in
      let* rules = List.monad_map decode_rule rules in
      ret (sg, ty, sh, cs, cl, rules)
    end
  in
  let jdg s = apps (mkglob' s) [| sg ; ty ; cs ; sh |] in
  let jdg_type = apps (mkglob' C.Jdg.jdg_type) [| sh ; ty |] in
  let rule_desc_ty = apps (mkglob' C.Jdg.rule_desc) [| sg ; ty ; sh |] in
  (* The constants the statements may unfold, the type of the relation (from
    the shapes) and of its contexts. *)
  let transparent, arity, ctx_ty =
    monad_run begin
      (* The constants which stay folded in the statements: the description, the
        operations of the syntax, the renamings, the lifting of substitutions,
        the generic judgment [J], and [Nat.sub] which would otherwise pollute
        [csub]. *)
      let* ops = decode_cs_ops cs in
      let* opaque = List.monad_map head_const (desc :: ops) in
      let opaque =
        List.filter_map (fun c -> c) opaque @
        List.map (fun g -> const_of_ref (Lazy.force g)) [
          C.rid ;
          C.rshift ;
          C.rcons ;
          C.rcomp ;
          C.up_ren ;
          C.Jdg.cup_subst ;
          C.Jdg.j ;
          C.sub
        ]
      in
      (* Those reachable from the library's definitions and the instance, but
        not those of the user's parameters. *)
      let* transparent =
        constants_closure (
          jdg C.Jdg.rule_desc_type ::
          jdg C.Jdg.var_rule_type ::
          jdg C.Jdg.pred_obl ::
          jdg C.Jdg.obligations ::
          jdg C.Jdg.preserve_subst_jdg ::
          jdg_type ::
          List.map mkglob' [
            C.Jdg.hrule ;
            C.Jdg.hctor ;
            C.Jdg.hjdg ;
            C.Jdg.hjp ;
            C.Jdg.hext ;
            C.Jdg.hpred
          ]
        )
      in
      let transparent =
        List.filter (fun c -> not (List.mem c opaque)) transparent
      in
      let* arity = reduce_only transparent jdg_type in
      let* sigma = get_sigma in
      let _, ctx_ty, _ = EConstr.destProd sigma arity in
      ret (transparent, arity, ctx_ty)
    end
  in
  (* The constructor types of a relation [r]: the reduced [var_rule_type] and
    [rule_desc_type], with the meta-variables named as in the description. *)
  let var_type (r : EConstr.t) : EConstr.t m =
    reduce_only transparent (app (jdg C.Jdg.var_rule_type) r)
  in
  let rule_type (r : EConstr.t) (rd : rule) : EConstr.t m =
    let* t =
      prod "Γ" ctx_ty @@ fun g ->
        ret @@
        apps (jdg C.Jdg.rule_desc_type) [| r ; rd.r_term ; EConstr.mkVar g |]
    in
    let* t = reduce_only transparent t in
    rename_binders (None :: List.map (fun x -> Some x) rd.r_binders) t
  in
  (* The inductive. *)
  let ctor_names =
    mk "_var" :: List.map (fun rd -> Names.Id.of_string_soft rd.r_name) rules
  in
  let ctor_types =
    (fun ind -> var_type (EConstr.mkVar ind)) ::
    List.map (fun rd ind -> rule_type (EConstr.mkVar ind) rd) rules
  in
  let ind = monad_run @@ declare_ind name arity ctor_names ctor_types in
  let r = mkind ind in
  let ctor i = mkctor (ind, i) in
  let stmt s = ret @@ apps (jdg s) [| desc ; r |] in
  (* [R_wf : wf_desc d], using tactic [JdgDesc.wf_desc_tac]. *)
  let wf =
    lemma (sname ^ "_wf")
      (ret @@ apps (mkglob' C.Jdg.wf_desc) [| sg ; ty ; sh ; desc |])
      (run_ltac "JdgDesc" "wf_desc_tac" [])
  in
  (* [R_rules : rules_type d R], the [Forall] built from the constructors. *)
  let rules_lemma =
    let pred =
      monad_run begin
        lambda "rd" rule_desc_ty @@ fun rd ->
        prod "Γ" ctx_ty @@ fun g ->
        ret @@
        apps (jdg C.Jdg.rule_desc_type) [|
          r ;
          EConstr.mkVar rd ;
          EConstr.mkVar g
        |]
      end
    in
    let rec build i = function
      | [] -> apps (mkglob' C.Jdg.forall_nil) [| rule_desc_ty ; pred |]
      | rd :: rest ->
        apps (mkglob' C.Jdg.forall_cons) [|
          rule_desc_ty ;
          pred ;
          rd.r_term ;
          mklist rule_desc_ty (List.map (fun rd -> rd.r_term) rest) ;
          ctor (i + 2) ;
          build (i + 1) rest
        |]
    in
    lemma (sname ^ "_rules")
      (stmt C.Jdg.rules_type)
      (Tactics.exact_check (build 0 rules))
  in
  (* [R_sound : sound_jdg d R], from the induction principle of [R], whose type
    is convertible to [ind_type d R]. *)
  let sound =
    let scheme =
      Nametab.locate_constant (Libnames.qualid_of_ident (mk "_ind"))
    in
    lemma (sname ^ "_sound")
      (stmt C.Jdg.sound_jdg)
      (Tactics.exact_check (
        apps (jdg C.Jdg.sound_of_ind) [|
          desc ;
          cl ;
          r ;
          mkconst scheme
        |]
      ))
  in
  (* [R_complete : complete_jdg d R]. *)
  let complete =
    lemma (sname ^ "_complete")
      (stmt C.Jdg.complete_jdg)
      (Tactics.exact_check (
        apps (jdg C.Jdg.jdg_complete) [|
          desc ;
          cl ;
          r ;
          ctor 1 ;
          mkconst rules_lemma ;
          mkconst wf
        |]
      ))
  in
  (* The obligations, as the positions [(r, i)] of the predicate premises
    (rule [r] of the description, premise [i]); [R_obls_wf] checks the list
    by computation. [R_obls : Prop] is their conjunction, reduced (with the
    description unfolded), declared as a class so that the user proves it
    once as an instance, and [R_subst : ∀ {H : R_obls}, preserve_subst_jdg R]
    finds it by resolution. No class when there is no obligation. *)
  let _subst =
    let obls =
      List.concat (List.mapi (fun r rd ->
        List.map (fun i -> (r, rd, i)) rd.r_preds) rules
      )
    in
    let nat_ty = mkglob' C.nat in
    let pos_ty = apps (mkglob' C.prod) [| nat_ty ; nat_ty |] in
    let ps =
      mklist pos_ty (List.map (fun (r, _, i) ->
        apps (mkglob' C.pair) [| nat_ty ; nat_ty ; mknat r ; mknat i |]) obls)
    in
    let ok =
      lemma (sname ^ "_obls_wf")
        (ret @@ apps (mkglob' C.Jdg.obls_ok) [| sg ; ty ; sh ; desc ; ps |])
        (run_ltac "JdgDesc" "wf_desc_tac" [])
    in
    let stmt =
      let* cs_const = head_const cs in
      let transp = List.map (fun g -> const_of_ref (Lazy.force g)) [
        C.Jdg.preserve_subst_jdg ;
        C.CS.csubstitute
      ] in
      let transp = match cs_const with Some c -> c :: transp | None -> transp in
      reduce_only (transp @ transparent) (app (jdg C.Jdg.preserve_subst_jdg) r)
    in
    let proof h =
      apps (jdg C.Jdg.gen_preserve_subst) [|
        desc ; cl ; r ; mkconst sound ; mkconst complete ; ps ; mkconst ok ; h
      |]
    in
    if obls = [] then
      ignore (lemma (sname ^ "_subst") stmt
        (Tactics.exact_check (proof (mkglob (Rocqlib.lib_ref "core.True.I")))))
    else begin
      (* The conjunction of the obligations, each with the binders of its
        rule *)
      let rename_obls (t : EConstr.t) : EConstr.t m =
        let* sigma = get_sigma in
        let rec go t = function
          | [] -> ret t
          | [ (_, rd, _) ] ->
            rename_binders (List.map (fun x -> Some x) rd.r_binders) t
          | (_, rd, _) :: obls ->
            match EConstr.decompose_app sigma t with
            | h, [| a ; b |] ->
              let* a =
                rename_binders (List.map (fun x -> Some x) rd.r_binders) a
              in
              let* b = go b obls in
              ret (apps h [| a ; b |])
            | _ -> ret t
        in
        go t obls
      in
      let obls_def =
        def (sname ^ "_obligations") begin
          let* desc_const = head_const desc in
          let transparent =
            match desc_const with Some c -> c :: transparent | None -> transparent
          in
          let* t =
            reduce_only transparent
              (apps (jdg C.Jdg.obligations) [| desc ; r ; ps |])
          in
          rename_obls t
        end
      in
      Record.declare_existing_class (Names.GlobRef.ConstRef obls_def) ;
      let subst =
        lemma (sname ^ "_subst")
          (let* concl = stmt in prod "H" (mkconst obls_def) (fun _ -> ret concl))
          (Tactics.exact_check
            (monad_run (lambda "H" (mkconst obls_def) (fun h ->
              ret (proof (EConstr.mkVar h))))))
      in
      Impargs.declare_manual_implicits false (Names.GlobRef.ConstRef subst)
        [ CAst.make (Some (Names.Name (Names.Id.of_string "H"), true)) ]
    end
  in
  ()

